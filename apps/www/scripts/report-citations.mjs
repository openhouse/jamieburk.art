import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, "..");
const repoRoot = path.resolve(appRoot, "../..");
const knowledgeBankDir = path.join(appRoot, "src/data/knowledge-bank");

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(knowledgeBankDir, relativePath), "utf8"));
}

function mapById(records) {
  return new Map(records.map((record) => [record.id, record]));
}

function slugifyPage(page) {
  return page.replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").toLowerCase() || "page";
}

function project(record) {
  const pageSlug = slugifyPage(record.page);
  const references = [];
  const referenceByGroup = new Map();

  for (const occurrence of record.occurrences) {
    const existing = referenceByGroup.get(occurrence.citationGroupId);
    const anchor = `cite-${pageSlug}-${occurrence.citationKey}`;

    if (existing) {
      existing.citationAnchors.push(anchor);
      continue;
    }

    const reference = {
      citationGroupId: occurrence.citationGroupId,
      number: references.length + 1,
      referenceId: `note-${pageSlug}-${occurrence.citationGroupId.toLowerCase()}`,
      citationAnchors: [anchor]
    };
    references.push(reference);
    referenceByGroup.set(occurrence.citationGroupId, reference);
  }

  return { page: record.page, references };
}

function sourceLabelForEvidence(evidenceRecord, sourceById, assetById) {
  if (evidenceRecord.target.kind === "source") {
    const source = sourceById.get(evidenceRecord.target.id);
    return `${source.id} - ${source.publisher}: ${source.title}`;
  }

  if (evidenceRecord.target.kind === "asset") {
    const asset = assetById.get(evidenceRecord.target.id);
    return `${asset.id} - ${asset.title}`;
  }

  return `${evidenceRecord.target.id} - documented research run`;
}

const sources = readJson("sources.json");
const assets = readJson("assets.json");
const claims = readJson("claims.json");
const evidence = readJson("evidence.json");
const researchRuns = readJson("research-runs.json");
const corrections = readJson("corrections.json");
const citationGroups = readJson("citation-groups.json");
const projectionFiles = fs
  .readdirSync(path.join(knowledgeBankDir, "page-projections"))
  .filter((file) => file.endsWith(".json"))
  .sort();
const projections = projectionFiles.map((file) => readJson(`page-projections/${file}`));

const sourceById = mapById(sources);
const assetById = mapById(assets);
const claimById = mapById(claims);
const evidenceById = mapById(evidence);
const citationGroupById = mapById(citationGroups);

const lines = [
  "# Citation Report",
  "",
  "Generated by `npm run report:citations`. This is a public-safe report: it lists claim IDs, public source labels, and boundaries without publishing private file paths or private artifacts.",
  "",
  "## Summary",
  "",
  `- Claims: ${claims.length}`,
  `- Evidence records: ${evidence.length}`,
  `- Sources: ${sources.length}`,
  `- Assets: ${assets.length}`,
  `- Research runs: ${researchRuns.length}`,
  `- Citation groups: ${citationGroups.length}`,
  `- Page projections: ${projections.length}`,
  ""
];

for (const projectionRecord of projections) {
  const projection = project(projectionRecord);

  lines.push(`## ${projection.page}`, "");

  for (const reference of projection.references) {
    const group = citationGroupById.get(reference.citationGroupId);
    const claimsForGroup = group.claimIds.map((claimId) => claimById.get(claimId));

    lines.push(`### [${reference.number}] ${group.title}`, "");
    lines.push(`- Citation group: \`${group.id}\``);
    lines.push(`- Reference id: \`${reference.referenceId}\``);
    lines.push(`- Claim ids: ${group.claimIds.map((claimId) => `\`${claimId}\``).join(", ")}`);
    lines.push(`- Visibility: ${group.visibility}`);
    lines.push(`- Public note: ${group.publicNote}`);

    if (group.boundaryNote) {
      lines.push(`- Boundary: ${group.boundaryNote}`);
    }

    lines.push("- Projected wording:");
    for (const claim of claimsForGroup) {
      const wording = claim.publicWording.portfolio ?? claim.publicWording.technicalOperations ?? claim.canonical;
      lines.push(`  - ${wording}`);
    }

    lines.push("- Evidence:");
    for (const evidenceId of group.sourceOrder) {
      const evidenceRecord = evidenceById.get(evidenceId);
      lines.push(`  - \`${evidenceId}\`: ${sourceLabelForEvidence(evidenceRecord, sourceById, assetById)}`);
    }

    lines.push("");
  }
}

lines.push("## Corrections", "");

for (const correction of corrections) {
  lines.push(
    `- \`${correction.id}\`: ${correction.surface} changed from \`${correction.previousValue}\` to \`${correction.correctedValue}\` (${correction.status}).`
  );
}

lines.push("", "## Research Boundaries", "");

for (const run of researchRuns) {
  lines.push(`- \`${run.id}\`: ${run.publicCitation}`);
  lines.push(`  - Limit: ${run.epistemicLimit}`);
  lines.push(
    `  - Counts: ${Object.entries(run.counts)
      .map(([key, value]) => `${key}=${value}`)
      .join(", ")}`
  );
}

lines.push("", "## Private Or Restricted Evidence", "");

const privateSources = sources.filter((source) => source.visibility !== "public");
const privateAssets = assets.filter((asset) => asset.visibility !== "public");

if (!privateSources.length && !privateAssets.length) {
  lines.push("- None.");
} else {
  for (const source of privateSources) {
    lines.push(`- Source \`${source.id}\`: ${source.publicCitation} ${source.citationMode === "description-only" ? "(description-only)" : ""}`);
  }

  for (const asset of privateAssets) {
    lines.push(`- Asset \`${asset.id}\`: ${asset.title}; no public asset URL is published.`);
  }
}

lines.push("", "## Non-Public Citation Groups", "");

for (const group of citationGroups.filter((record) => record.visibility !== "public")) {
  lines.push(`- \`${group.id}\`: ${group.publicNote}`);
}

const reportPath = path.join(repoRoot, "reports/citations.md");
fs.mkdirSync(path.dirname(reportPath), { recursive: true });
fs.writeFileSync(reportPath, `${lines.join("\n")}\n`);

console.log(`Citation report written to ${path.relative(repoRoot, reportPath)}`);
